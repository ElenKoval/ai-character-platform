/**
 * No chapter-state block — knowledge is fixed in the core.
 */
export function pickPakState() {
  return {
    id: "live",
    min: 0,
    max: 13,
    label: "Живой разговор",
    memories: [],
    emotionText: "",
    text: "",
  };
}

/** Thread / ask_more: keep short, same dry voice. */
export function blockPakThreadMode(ctx = {}) {
  const mode = String(ctx.mode || "talk").toLowerCase().trim();
  const isThread =
    mode === "thread" ||
    mode === "твоя нить" ||
    mode === "your_thread" ||
    mode === "your-thread" ||
    mode === "ask_more" ||
    mode === "ask-more" ||
    mode === "спросить ещё" ||
    mode === "crew";
  if (!isThread) return "";

  const label =
    mode === "ask_more" || mode === "ask-more" || mode === "спросить ещё" || mode === "crew"
      ? "Спросить ещё"
      : "Твоя Нить";

  return `## Режим «${label}»
Человек назвал, чего хочет слишком сильно. Спроси одно: что именно. Скажи, что тут лишнее напряжение и где бы «резал» – образно про Жажду, не про вред телу. Одно конкретное действие. Без метафор, без утешений, максимум два коротких предложения.`;
}

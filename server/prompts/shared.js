/** Mode bodies only — assemble one at request time. */
export const MODE_BODIES = {
  talk: `**Разговор.** Человек пришёл поговорить. Он может шутить, спорить, говорить о книге или о своей жизни. Не тяни всё к одной теме.`,
  reader: `**Из читалки.** Человек сейчас читает главу {текущая_глава}. Можешь коротко зацепиться за неё. Не пересказывай.`,
  thread: `**Твоя Нить.** Первое сообщение – то, чего человек хочет слишком сильно. 2–4 предложения: что ты видишь в этом желании и что бы ты сделал. Без советов «как жить». Один вопрос максимум.`,
  ask_more: `**Спросить ещё (команда).** То же, что «Твоя Нить», но 1–3 предложения.`,
};

export function blockModeOnly(ctx) {
  const c = normalizeCtx(ctx);
  const current =
    c.currentChapter == null ? String(c.readChapter) : String(c.currentChapter);
  const body = (MODE_BODIES[c.mode] || MODE_BODIES.talk).replaceAll(
    "{текущая_глава}",
    current
  );
  return `## 4. РЕЖИМ: ${modeLabel(c.mode)}

${body}`;
}


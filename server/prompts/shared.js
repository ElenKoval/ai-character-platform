/** Client/API aliases → canonical hybrid id (story-meta uses apiId "drpak"). */
export const HYBRID_ALIASES = {
  drpak: "pak",
  shinybro: "shiny_bro",
  mushroom: "talk_mushroom",
  forest: "angry_forest",
  kiper: "keeper",
};

export function resolveHybridId(characterId) {
  const id = (characterId || "").toLowerCase().trim().replace(/\s+/g, "_");
  return HYBRID_ALIASES[id] || id;
}

export function normalizeCtx(raw = {}) {
  const readChapter = clampInt(raw.readChapter, 0, 13, 0);
  const currentChapter =
    raw.currentChapter == null || raw.currentChapter === ""
      ? null
      : clampInt(raw.currentChapter, 0, 13, readChapter);
  const mode = normalizeMode(raw.mode);
  const language = raw.language === "en" ? "en" : "ru";
  const moodNow =
    typeof raw.moodNow === "string" && raw.moodNow.trim()
      ? raw.moodNow.trim()
      : typeof raw.moodNow === "number" && Number.isFinite(raw.moodNow)
        ? raw.moodNow
        : typeof raw.moodNowIndex === "number" && Number.isFinite(raw.moodNowIndex)
          ? raw.moodNowIndex
          : null;
  return { readChapter, currentChapter, mode, language, moodNow };
}

export function isHybridCharacter(characterId) {
  return HYBRID_IDS.has(resolveHybridId(characterId));
}

function clampInt(value, min, max, fallback) {
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.min(max, Math.max(min, Math.trunc(n)));
}

function normalizeMode(mode) {
  const m = String(mode || "talk").toLowerCase().trim();
  if (m === "reader" || m === "из читалки") return "reader";
  if (m === "thread" || m === "твоя нить" || m === "your_thread" || m === "your-thread")
    return "thread";
  if (m === "ask_more" || m === "ask-more" || m === "спросить ещё" || m === "crew")
    return "ask_more";
  return "talk";
}

export function modeLabel(mode) {
  switch (normalizeMode(mode)) {
    case "reader":
      return "Из читалки";
    case "thread":
      return "Твоя Нить";
    case "ask_more":
      return "Спросить ещё";
    default:
      return "Разговор";
  }
}

export function languageLabel(language) {
  return language === "en" ? "английский" : "русский";
}

